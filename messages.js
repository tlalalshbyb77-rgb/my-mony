  /**
   * يختار رسالة عشوائية من مصفوفة، مع تجاهل آخر الرسائل المعروضة.
   */
  function pickMessage(pool, recent) {
    if (!Array.isArray(pool) || pool.length === 0) {
      return '';
    }
    const recentList = Array.isArray(recent) ? recent : [];
    const fresh = pool.filter((message) => !recentList.includes(message));
    const source = fresh.length > 0 ? fresh : pool;
    return source[Math.floor(Math.random() * source.length)];
  }

  /**
   * يستبدل المتغيرات العربية داخل الرسالة بقيمها الفعلية.
   */
  function fillMessage(template, values) {
    const dictionary = values || {};
    return String(template || '').replace(/\{([^}]+)\}/g, (match, key) => {
      const value = dictionary[key];
      return value === undefined || value === null ? '' : String(value);
    });
  }

  window.WalletMessages = {
    banks,
    pick: pickMessage,
    fill: fillMessage
  };
